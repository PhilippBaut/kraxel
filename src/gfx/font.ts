export function textWidth(s: string): number {
  const n = [...s].length;
  return n ? n * ADVANCE - 1 : 0;
}

/** Zeichen ohne Glyphe, jedes nur einmal, in der Reihenfolge des Auftretens. */
export function missingGlyphs(s: string): string[] {
  return [...new Set(s)].filter((ch) => !(ch in FONT5));
}
